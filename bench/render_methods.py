"""bench/METHODS.md from bench/results/methods.json (written by bench/methods.py; never edited by hand)."""
from __future__ import annotations

import json
from pathlib import Path

TITLES = {"candidates.method": "Candidate generation", "features.string_similarity": "String similarity",
          "matcher.estimator": "Estimator", "decision.cardinality": "Cardinality policy"}
SHORT = {"febrl4_half_unmatched": "FEBRL4", "bpid": "BPID", "abt_buy": "Abt-Buy", "leipzig_affiliations": "Leipzig"}


def render(results: Path, dest: Path) -> None:
    d = json.loads(results.read_text())
    lines = ["# Method choices (ZR-3a)", "",
             "*Generated by `bench/methods.py` from `bench/results/methods.json` — do not edit by hand.*", "",
             f"Spark {d.get('meta', {}).get('spark')} · generated {d.get('meta', {}).get('generated')} · every "
             "choice is selected on **validation** data (TEST is left for ZR-3's final table). The winner of each "
             "choice is the highest mean over the corpora it applies to; a tie keeps the current default. The winners "
             "are the defaults in `src/lakematch/config.py`.", ""]
    for key in TITLES:
        block = d.get("comparisons", {}).get(key)
        lines += [f"## {TITLES[key]} — `{key}`", ""]
        if not block:
            lines += ["*Not run yet.*", ""]
            continue
        corp = list(block["per_corpus"])
        metric = block["metric"]
        if key == "candidates.method":
            lines += ["Candidate recall at an equal pair budget: every method's proposals are ranked by the same IDF "
                      "gram cosine and cut to the budget below; recall = true pairs of VALID left records that survive. "
                      f"`union` = {' + '.join(block.get('union_of', []))}. Budget: " +
                      "; ".join(f"{SHORT[c]} {b}" for c, b in block["budget"].items()) + ".", ""]
            lines += ["| Method | " + " | ".join(f"{SHORT[c]} recall · proposals · s" for c in corp) + " | Mean recall |",
                      "|---|" + "---:|" * (len(corp) + 1)]
            for m, mean in block["mean"].items():
                cells = []
                for c in corp:
                    r = block["per_corpus"][c]["choices"][m]
                    cells.append(f"{r['recall_at_budget']:.4f} · {r['proposals']:,} · {r['wall_s']}")
                name = f"**{m}**" if m == block["winner"] else m
                lines.append(f"| {name} | " + " | ".join(cells) + f" | {mean:.4f} |")
        else:
            lines += ["End-to-end F1 on VALID (95 % bootstrap interval), everything else at its default, "
                      f"candidates from `{d.get('candidate_method_used_downstream')}`.", ""]
            lines += ["| Choice | " + " | ".join(SHORT[c] for c in corp) + " | Mean |", "|---|" + "---:|" * (len(corp) + 1)]
            for ch, mean in block["mean"].items():
                cells = []
                for c in corp:
                    r = block["per_corpus"][c]["choices"][ch]
                    cells.append(f"{r[metric]:.4f} [{r['ci95'][0]:.3f}, {r['ci95'][1]:.3f}]")
                name = f"**{ch}**" if ch == block["winner"] else ch
                lines.append(f"| {name} | " + " | ".join(cells) + f" | {mean:.4f} |")
        lines += ["", f"Winner: **{block['winner']}**."]
        if block.get("best_unconstrained") and block["best_unconstrained"] != block["winner"]:
            lines += ["", f"> The highest mean is `{block['best_unconstrained']}`, but only "
                      f"{', '.join(f'`{c}`' for c in block['eligible_as_default'])} may be a default on Spark "
                      f"{d.get('meta', {}).get('spark')}: D07 forbids a default path that depends on Jaro-Winkler, a UDF "
                      "before Spark 4.3. It stays available behind `features.udf_features`; the Spark 4.3 watcher "
                      "triggers the re-decision once it is a built-in."]
        lines += [""]
    dest.write_text("\n".join(lines))
