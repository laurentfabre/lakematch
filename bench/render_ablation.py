"""bench/ABLATION.md from bench/results/ablation.json (written by bench/ablation.py; never edited by hand)."""
from __future__ import annotations

import json
from pathlib import Path

TITLES = {"febrl4_half_unmatched": "FEBRL4, half the partners removed", "bpid": "BPID (person profiles)",
          "leipzig_affiliations": "Leipzig Affiliations (organisation names)", "abt_buy": "Abt-Buy (product titles)"}


def _table(block: dict) -> list[str]:
    out = ["| Variant | Features | F1 | 95 % CI | Δ vs reference | Δ 95 % CI | P | R |",
           "|---|---:|---:|---|---:|---|---:|---:|"]
    for r in block["rows"]:
        delta = f"{r['delta']:+.4f}" if "delta" in r else "—"
        dci = f"[{r['delta_ci95'][0]:+.4f}, {r['delta_ci95'][1]:+.4f}]" if "delta_ci95" in r else "—"
        name = f"**{r['variant']}**" if r["variant"] == "reference" else r["variant"]
        out.append(f"| {name} | {r['n_features']} | {r['f1']:.4f} | [{r['ci95'][0]:.4f}, {r['ci95'][1]:.4f}] | "
                   f"{delta} | {dci} | {r['precision']:.3f} | {r['recall']:.3f} |")
    return out


def render(results: Path, dest: Path) -> None:
    d = json.loads(results.read_text())
    meta = d.get("meta", {})
    lines = [
        "# Feature ablation (ZR-2)",
        "",
        "*Generated by `bench/ablation.py` from `bench/results/ablation.json` — do not edit by hand.*",
        "",
        f"Spark {meta.get('spark')} · estimator {meta.get('estimator')} · {meta.get('bootstrap')} bootstrap "
        f"resamples · generated {meta.get('generated')}.",
        "",
        "Each corpus computes the full comparison vector once; every row trains the default estimator on a subset of "
        "its columns, picks the threshold on VALID and reports TEST. The **reference** row is the default feature set "
        f"({', '.join(meta.get('reference_families', []))}); `- family` removes one family, `+ … (UDF)` adds the "
        "optional UDF features, `+ embedding …` adds the embedding cosine. Δ is the difference from the reference, "
        "with a paired bootstrap interval (same resamples): an interval that excludes 0 is a measured effect.",
        "",
    ]
    for key in ("febrl4_half_unmatched", "bpid", "leipzig_affiliations", "abt_buy"):
        if key not in d:
            lines += [f"## {TITLES[key]}", "", "*Not run yet.*", ""]
            continue
        blocks = ([("all fields", d[key]["all_fields"]), ("SSN hidden", d[key]["ssn_hidden"])]
                  if key == "febrl4_half_unmatched" else [(None, d[key])])
        lines += [f"## {TITLES[key]}", ""]
        for label, block in blocks:
            if label:
                lines += [f"### {label}", ""]
            info = [f"{block['test_units']} test units ({block['unit']})"]
            if "candidate_recall" in block:
                info.append(f"candidate recall {block['candidate_recall']:.4f}, {block['labels']} labelled pairs")
            info += block.get("notes", [])
            lines += ["; ".join(info) + ".", ""] + _table(block) + [""]
            top = block["rows"][0].get("top_features")
            if top:
                lines += ["The reference model leans on: " + ", ".join(f"`{c}` {v:.2f}" for c, v in top) +
                          " (GBT importances). A family the model does not use removes at Δ 0 exactly; "
                          "redundant families substitute for one another.", ""]
            if block.get("embedding_models"):
                lines += ["| Embedding model | Dimensions | Texts encoded | Encode cost, s per 10^5 records |",
                          "|---|---:|---:|---:|"]
                for m in block["embedding_models"]:
                    lines.append(f"| {m['model']} | {m['dims']} | {m['texts']} | {m['encode_s_per_1e5_records']} |")
                lines.append("")
    e = d.get("embedding_decision", {})
    lines += ["## Decision D12 — embeddings on by default?", ""]
    if e.get("kept_on_by_default") is None:
        lines += ["*Waiting for both embedding corpora.*", ""]
    else:
        lines += [f"Rule: {e['rule']}.", "",
                  f"Model chosen on {e['chosen_on']}: **{e['winner_model']}**.", "",
                  "| Model | Mean VALID F1 | TEST Δ Leipzig | TEST Δ Abt-Buy |", "|---|---:|---:|---:|"]
        for m, s in e["models"].items():
            td, ci = s["test_delta"], s["test_delta_ci95"]
            cell = lambda c: f"{td[c]:+.4f} [{ci[c][0]:+.4f}, {ci[c][1]:+.4f}]"
            lines.append(f"| {m} | {s['valid_f1_mean']:.4f} | {cell('leipzig_affiliations')} | {cell('abt_buy')} |")
        verdict = "kept **on** by default" if e["kept_on_by_default"] else "turned **off** by default"
        lines += ["", f"Verdict: the embedding feature is {verdict} for organisation and title fields "
                      "(`features.embeddings.fields_of_type` in `config.py`).", ""]
    dest.write_text("\n".join(lines))
